-- A chave SUPABASE_SERVICE_ROLE_KEY deve ficar somente no servidor, nunca no navegador.

CREATE TABLE IF NOT EXISTS public.sc_categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sc_clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  telefone TEXT NOT NULL,
  cidade TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sc_fornecedores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razao_social TEXT NOT NULL,
  cnpj TEXT NOT NULL,
  email TEXT NOT NULL,
  telefone TEXT NOT NULL,
  cidade TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sc_produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  descricao TEXT NOT NULL,
  preco NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
  estoque INTEGER NOT NULL CHECK (estoque >= 0),
  categoria TEXT NOT NULL
);

ALTER TABLE public.sc_categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sc_clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sc_fornecedores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sc_produtos ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.sc_categorias, public.sc_clientes, public.sc_fornecedores, public.sc_produtos TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
